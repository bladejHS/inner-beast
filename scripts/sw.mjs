// Writes dist/sw.js: precaches every built file under a version derived from their content.
// A new deploy = a new version: the next launch installs it, the one after runs it.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const DIST = 'dist';

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(DIST)
  .filter((f) => !/sw\.js$|\.map$|OFL\.txt$/.test(f))
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(f));
const version = hash.digest('hex').slice(0, 12);
const urls = files.map((f) => './' + relative(DIST, f).replace(/\\/g, '/')).map((u) => (u === './index.html' ? './' : u));

const sw = `// Generated by scripts/sw.mjs
const V = 'beast-${version}';
const ASSETS = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(V).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((ks) => Promise.all(ks.filter((k) => k.startsWith('beast-') && k !== V).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const r = e.request;
  if (r.method !== 'GET') return;
  const url = new URL(r.url);
  if (url.origin !== location.origin) return;
  if (r.mode === 'navigate') {
    e.respondWith(caches.match('./').then((m) => m || fetch(r)));
    return;
  }
  e.respondWith(caches.match(r, { ignoreSearch: true }).then((m) => m || fetch(r)));
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files, version ${version}`);
